# Задача 4. Минимальное число платформ
# ============================================================
# Условие:
#   Даны время прибытия и отправления поездов на станции
#   (в минутах от начала суток). Определите минимальное
#   количество платформ, чтобы все поезда могли остановиться.
#
# Пример:
#   arrivals   = [900, 940, 950, 1100, 1500, 1800]
#   departures = [910, 1200, 1120, 1130, 1900, 2000]
#   Ответ: 3
#
# Жадная идея:
#   отсортировать события: прибытие — +1, отправление — -1.
#   Пройти по событиям, поддерживая текущее число занятых
#   платформ и максимум за всё время.
#
# Вопрос: почему при равном времени прибытия и отправления
#   отправление должно обрабатываться раньше прибытия?
# Ответ: поезд, который уезжает в эту минуту, освобождает
#   платформу, и приехавший поезд может сразу её занять.
#   Если сначала посчитать прибытие, мы на мгновение получим
#   лишнюю занятую платформу и ответ будет завышен.
#
# Сложность: O(n log n), память O(n).


def min_platforms(arrivals: list, departures: list) -> int:
    """Вернуть минимальное число платформ."""
    arr = sorted(arrivals)
    dep = sorted(departures)

    i = 0  # индекс следующего прибытия
    j = 0  # индекс следующего отправления
    current = 0   # сколько платформ занято сейчас
    max_needed = 0

    while i < len(arr):
        if arr[i] < dep[j]:
            # раньше происходит прибытие — занимаем платформу
            current = current + 1
            i = i + 1
            if current > max_needed:
                max_needed = current
        else:
            # раньше (или одновременно) отправление — освобождаем
            current = current - 1
            j = j + 1

    return max_needed


