# ============================================================
# Задача 1. Размен монет
# ============================================================
# Условие:
#   Дана сумма S и набор номиналов монет. Требуется выдать
#   сумму минимальным количеством монет.
#
# Жадная стратегия:
#   1) взять самую крупную монету, не превышающую остаток;
#   2) вычесть её из суммы;
#   3) повторять до нуля.
#
# Пример:
#   S = 87, coins = [50, 10, 5, 1]
#   Ответ: 7 монет (50 + 10 + 10 + 10 + 5 + 1 + 1)
#
# Сложность: O(k log k + n), где k — число номиналов,
#            n — количество монет в ответе.


def min_coins(amount: int, coins: list) -> int:
    """Вернуть минимальное число монет или -1, если нельзя."""
    # сортируем номиналы от большего к меньшему
    sorted_coins = sorted(coins, reverse=True)
    count = 0

    for coin in sorted_coins:
        # берём эту монету, пока она помещается в остаток
        while amount >= coin:
            amount = amount - coin
            count = count + 1

    # если что-то осталось, выдать сумму этими монетами нельзя
    if amount > 0:
        return -1
    return count


# ============================================================
# Задача 2. Выбор интервалов
# ============================================================
# Условие:
#   Даны интервалы времени. Нужно выбрать максимальное
#   количество непересекающихся интервалов.
#
# Жадная стратегия:
#   1) отсортировать интервалы по времени окончания;
#   2) брать интервал, если он начинается не раньше
#      окончания предыдущего.
#
# Пример:
#   intervals = [(1,4),(3,5),(0,6),(5,7),(3,9),(5,9),(6,10),(8,11)]
#   Ответ: 4
#
# Сложность: O(n log n).


def get_end(interval):
    """Вернуть время окончания интервала (нужно для сортировки)."""
    return interval[1]


def max_intervals(intervals: list) -> int:
    """Вернуть максимальное число непересекающихся интервалов."""
    sorted_intervals = sorted(intervals, key=get_end)

    count = 0
    last_end = None  # окончание последнего выбранного интервала

    for start, end in sorted_intervals:
        # первый интервал берём всегда, остальные — если не пересекаются
        if last_end is None or start >= last_end:
            count = count + 1
            last_end = end

    return count


# ============================================================
# Задача 3. Дробный рюкзак
# ============================================================
# Условие:
#   Есть рюкзак вместимостью W и предметы с весом wi и
#   стоимостью vi. Можно брать части предметов.
#   Максимизировать суммарную стоимость.
#
# Жадная стратегия:
#   1) вычислить удельную стоимость vi/wi;
#   2) сортировать по убыванию;
#   3) брать предметы, пока есть место;
#   4) последний предмет — частично.
#
# Сложность: O(n log n).


def fractional_knapsack(capacity: float, items: list) -> float:
    """
    items: список кортежей (weight, value).
    Вернуть максимальную суммарную стоимость.
    """
    # для каждого предмета считаем цену одной единицы веса
    ratios = []
    for weight, value in items:
        ratio = value / weight
        ratios.append((ratio, weight, value))

    # сначала самые "дорогие" на единицу веса
    ratios.sort(reverse=True)

    total_value = 0.0
    free_space = capacity

    for ratio, weight, value in ratios:
        if free_space <= 0:
            break  # рюкзак заполнен

        if weight <= free_space:
            # предмет помещается целиком
            total_value = total_value + value
            free_space = free_space - weight
        else:
            # берём только часть предмета, сколько влезет
            total_value = total_value + ratio * free_space
            free_space = 0

    return total_value


