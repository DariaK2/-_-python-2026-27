# ============================================================
# Задача 2.1. Время по секундам
# ============================================================
# Дано целое число секунд. Переведите его в формат ЧЧ:ММ:СС
# с помощью арифметических операций (// и %).
#
# Пример:
#   In: 3661
#   Out: 01:01:01


def seconds_to_hms(seconds: int) -> str:
    # в одном часе 3600 секунд
    hours = seconds // 3600
    # то, что осталось после целых часов, делим на 60 — это минуты
    minutes = (seconds % 3600) // 60
    # остаток от деления на 60 — это секунды
    secs = seconds % 60

    # :02d добавляет ведущий ноль, если число однозначное (1 -> 01)
    result = f"{hours:02d}:{minutes:02d}:{secs:02d}"
    return result


# ============================================================
# Задача 2.2. Сумма цифр трёхзначного числа
# ============================================================
# Дано трёхзначное число. Найдите сумму его цифр, используя
# только арифметические операции.
#
# Пример:
#   In: 456
#   Out: 15 (4 + 5 + 6)


def sum_digits(n: int) -> int:
    first = n // 100          # сотни: 456 // 100 = 4
    second = (n // 10) % 10   # десятки: 45 % 10 = 5
    third = n % 10            # единицы: 456 % 10 = 6

    total = first + second + third
    return total


# ============================================================
# Задача 2.3. Размен монет
# ============================================================
# Дана сумма в копейках. Определите минимальное количество
# монет номиналом 1, 5, 10, 50 копеек, чтобы выдать эту сумму.
#
# Пример:
#   In: 87
#   Out:
#     50: 1
#     10: 3
#     5: 1
#     1: 2


def coin_change(amount: int) -> dict:
    coins = [50, 10, 5, 1]
    result = {}

    for coin in coins:
        result[coin] = amount // coin
        amount = amount % coin

    return result


